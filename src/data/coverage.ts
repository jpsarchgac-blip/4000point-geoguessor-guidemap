export function isoToFlag(iso: string): string {
  return iso
    .toUpperCase()
    .replace(/[^A-Z]/g, '')
    .slice(0, 2)
    .replace(/./g, (ch) => String.fromCodePoint(127397 + ch.charCodeAt(0)))
}

export function featureIso(props: Record<string, unknown>): string | null {
  const a2 = String(props.ISO_A2 ?? '')
  const eh = String(props.ISO_A2_EH ?? '')
  if (a2 === 'CN-TW' || eh === 'TW') return 'TW'
  if (/^[A-Z]{2}$/.test(a2)) return a2
  if (/^[A-Z]{2}$/.test(eh)) return eh
  return null
}
